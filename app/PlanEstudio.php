<?php

namespace App;

use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\SoftDeletes;

class PlanEstudio extends Model
{
    use SoftDeletes;

    public function __construct(array $attributes = array())
    {
        parent::__construct($attributes);
    }

    //Mass Assignment
    protected $fillable = ['name', 'usu_alta_id', 'usu_mod_id', 'numero', 'plantel_id', 'total_materias_100', 'clave_sep_cert', 'nombre_sep_cert'];

    public function usu_alta()
    {
        return $this->hasOne('App\User', 'id', 'usu_alta_id');
    } // end

    public function usu_mod()
    {
        return $this->hasOne('App\User', 'id', 'usu_mod_id');
    } // end


    protected $dates = ['deleted_at'];

    // generated by relation command - Plantel,PlanEstudio - start
    public function plantel()
    {
        return $this->belongsTo('App\Plantel');
    } // end

    public function periodosEstudio()
    {
        return $this->belongsToMany('App\PeriodoEstudio');
    } // end
}
